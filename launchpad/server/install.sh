#!/usr/bin/env bash
# Installs or updates LaunchPad-INCUBICS on this server as an isolated Docker Compose project.
#
# Safe on a shared server:
#   - touches only this directory and the "launchpad" compose project (own network, own volumes)
#   - never stops, restarts or reconfigures any other container, nginx or service
#   - publishes exactly one thing on the host: this stack's own nginx container
#
# Usage:   ./install.sh            install, or update to the newest images
#          ./install.sh --check    only report what would happen, change nothing
#
# Optional environment: DOMAIN, LE_EMAIL, LAUNCHPAD_PORT, LAUNCHPAD_REGISTRY, LAUNCHPAD_VERSION, FORCE=1
set -euo pipefail
cd "$(dirname "$0")"

DOMAIN=${DOMAIN:-launchpad.incubics.com}
LE_EMAIL=${LE_EMAIL:-}
CHECK_ONLY=false
[ "${1:-}" = "--check" ] && CHECK_ONLY=true

say() { printf '\033[1;32m==>\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33mWARNING:\033[0m %s\n' "$*"; }
die() { printf '\033[1;31mERROR:\033[0m %s\n' "$*" >&2; exit 1; }

command -v docker >/dev/null || die "Docker is not installed. Install Docker Engine first; this script does not install system packages."
docker compose version >/dev/null 2>&1 || die "The Docker Compose plugin is missing (docker compose)."

port_busy() { ss -Hltn "sport = :$1" 2>/dev/null | grep -q .; }
port_owner() { ss -Hltnp "sport = :$1" 2>/dev/null | sed -n 's/.*users:(("\([^"]*\)".*/\1/p' | sort -u | paste -sd, -; }
ours_running() { [ -f .env ] && [ -n "$(docker compose ps -q nginx 2>/dev/null)" ]; }

# ---- memory check: the stack needs roughly 4 GB while starting -------------------------------
avail_mb=$(awk '/MemAvailable/ {print int($2/1024)}' /proc/meminfo)
say "Available memory: ${avail_mb} MB"
if ! ours_running && [ "$avail_mb" -lt 4096 ] && [ "${FORCE:-}" != "1" ]; then
  die "Less than 4 GB of memory is available. Starting LaunchPad could starve the other apps on this server. Free memory or re-run with FORCE=1."
fi

# ---- decide how this stack's nginx is exposed ------------------------------------------------
PORT=""
if [ -f .env ]; then
  MODE=$(sed -n 's/^LAUNCHPAD_MODE=//p' .env)
  say "Existing installation found (mode: $MODE); keeping its settings and secrets."
elif port_busy 80 || port_busy 443; then
  MODE=behind
  say "Ports 80/443 are already used on this server by: $(port_owner 80) $(port_owner 443)"
  say "LaunchPad's nginx will listen on 127.0.0.1 only and will not disturb it."
  PORT=${LAUNCHPAD_PORT:-18087}
  while port_busy "$PORT"; do PORT=$((PORT + 1)); done
  say "Chosen local port: 127.0.0.1:$PORT"
else
  MODE=edge
  say "Ports 80 and 443 are free: LaunchPad's own nginx will serve https://$DOMAIN directly."
fi

if $CHECK_ONLY; then
  say "Check only: nothing was changed. Containers currently on this server:"
  docker ps --format 'table {{.Names}}\t{{.Image}}\t{{.Ports}}' | head -40
  exit 0
fi

# ---- .env: generated once, never overwritten -------------------------------------------------
if [ ! -f .env ]; then
  rand() { openssl rand -hex 32; }
  cr_pass=$(rand)
  if [ "$MODE" = edge ]; then
    bind="0.0.0.0:80"; files="compose.yml:compose.edge.yml"
  else
    bind="127.0.0.1:$PORT"; files="compose.yml"
  fi
  umask 077
  cat > .env <<ENV
# Generated by install.sh. Contains secrets: keep private, back it up with the data volumes.
COMPOSE_FILE=$files
LAUNCHPAD_MODE=$MODE
LAUNCHPAD_REGISTRY=${LAUNCHPAD_REGISTRY:-ghcr.io/apptestify}
LAUNCHPAD_VERSION=${LAUNCHPAD_VERSION:-latest}
HULY_VERSION=v0.7.432
HOST_ADDRESS=$DOMAIN
SECURE=true
NGINX_HTTP_BIND=$bind
DEFAULT_LANGUAGE=en
LAST_NAME_FIRST=false
CR_DATABASE=defaultdb
CR_USERNAME=selfhost
CR_USER_PASSWORD=$cr_pass
CR_DB_URL=postgres://selfhost:$cr_pass@cockroach:26257/defaultdb
REDPANDA_ADMIN_USER=superadmin
REDPANDA_ADMIN_PWD=$(rand)
SECRET=$(rand)
ENV
  say "Wrote .env with freshly generated secrets."
fi
set -a; . ./.env; set +a

# ---- nginx config for this stack's own nginx -------------------------------------------------
write_http_conf() {
  cat > nginx/active.conf <<NGINX
server {
    listen 80;
    server_name $DOMAIN;
    location /.well-known/acme-challenge/ { root /var/www/certbot; }
    include /etc/nginx/launchpad/routes.inc;
}
NGINX
}
write_tls_conf() {
  cat > nginx/active.conf <<NGINX
server {
    listen 80;
    server_name $DOMAIN;
    location /.well-known/acme-challenge/ { root /var/www/certbot; }
    location / { return 301 https://\$host\$request_uri; }
}
server {
    listen 443 ssl;
    server_name $DOMAIN;
    ssl_certificate     /etc/letsencrypt/live/$DOMAIN/fullchain.pem;
    ssl_certificate_key /etc/letsencrypt/live/$DOMAIN/privkey.pem;
    include /etc/nginx/launchpad/routes.inc;
}
NGINX
}
[ -f nginx/active.conf ] || write_http_conf

# ---- images ----------------------------------------------------------------------------------
say "Pulling images (other containers on this server are not affected)..."
if ! docker compose pull --quiet; then
  die "Could not pull images. If $LAUNCHPAD_REGISTRY is private, run:  docker login ghcr.io -u <github-user>  (token with read:packages), then re-run."
fi

say "Starting the launchpad project..."
docker compose up -d

# ---- TLS when this stack owns 80/443 ---------------------------------------------------------
if [ "$MODE" = edge ] && ! docker compose exec -T nginx test -f "/etc/letsencrypt/live/$DOMAIN/fullchain.pem"; then
  say "Requesting a Let's Encrypt certificate for $DOMAIN..."
  email_arg="--register-unsafely-without-email"
  [ -n "$LE_EMAIL" ] && email_arg="--email $LE_EMAIL"
  # shellcheck disable=SC2086
  if docker compose run --no-deps --entrypoint certbot certbot certonly --webroot -w /var/www/certbot \
      -d "$DOMAIN" --agree-tos --non-interactive $email_arg; then
    write_tls_conf
    docker compose exec -T nginx nginx -t && docker compose exec -T nginx nginx -s reload
    say "HTTPS is active."
  else
    warn "Certificate request failed (is DNS for $DOMAIN pointing at this server?). The site is up on plain HTTP; re-run ./install.sh once DNS is correct."
  fi
fi

docker compose ps --format 'table {{.Name}}\t{{.Status}}'
echo
if [ "$MODE" = behind ]; then
  cat <<MSG
LaunchPad is running on http://$NGINX_HTTP_BIND (reachable from this server only).

Ports 80/443 belong to another program on this server, so one small addition is needed there to
send $DOMAIN to LaunchPad. For nginx, add this as a NEW file (do not edit existing sites), then
issue a certificate for $DOMAIN and reload:

    server {
        listen 80;
        server_name $DOMAIN;
        client_max_body_size 100M;
        location / {
            proxy_http_version 1.1;
            proxy_set_header Upgrade \$http_upgrade;
            proxy_set_header Connection "upgrade";
            proxy_set_header Host \$host;
            proxy_set_header X-Real-IP \$remote_addr;
            proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
            proxy_set_header X-Forwarded-Proto \$scheme;
            proxy_read_timeout 3600s;
            proxy_pass http://$NGINX_HTTP_BIND;
        }
    }
MSG
else
  echo "LaunchPad is running at https://$DOMAIN"
fi
